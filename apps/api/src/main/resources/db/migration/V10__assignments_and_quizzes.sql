CREATE TABLE assignments (
  id BIGINT NOT NULL AUTO_INCREMENT,
  class_id BIGINT NOT NULL,
  title VARCHAR(200) NOT NULL,
  description TEXT NULL,
  category ENUM('quiz','assignment','midterm','final') NOT NULL DEFAULT 'assignment',
  available_from DATETIME NULL,
  due_at DATETIME NOT NULL,
  allow_late BOOLEAN NOT NULL DEFAULT FALSE,
  late_due_at DATETIME NULL,
  late_penalty_percent INT UNSIGNED NOT NULL DEFAULT 0,
  max_attempts INT UNSIGNED NULL,
  score_policy ENUM('best','last') NOT NULL DEFAULT 'best',
  is_published BOOLEAN NOT NULL DEFAULT FALSE,
  created_by BIGINT NOT NULL,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  PRIMARY KEY (id),
  KEY ix_assignments_class_due (class_id, due_at),
  CONSTRAINT fk_assignments_class FOREIGN KEY (class_id) REFERENCES classes(id),
  CONSTRAINT fk_assignments_creator FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE assignment_questions (
  id BIGINT NOT NULL AUTO_INCREMENT,
  assignment_id BIGINT NOT NULL,
  question_id BIGINT NOT NULL,
  question_version_id BIGINT NULL,
  points DECIMAL(6,2) NOT NULL,
  position INT UNSIGNED NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_assignment_question (assignment_id, question_id),
  KEY ix_assignment_questions_order (assignment_id, position),
  CONSTRAINT fk_assignment_questions_assignment FOREIGN KEY (assignment_id) REFERENCES assignments(id) ON DELETE CASCADE,
  CONSTRAINT fk_assignment_questions_question FOREIGN KEY (question_id) REFERENCES questions(id),
  CONSTRAINT fk_assignment_questions_version FOREIGN KEY (question_version_id) REFERENCES question_versions(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE assignment_attempts (
  id BIGINT NOT NULL AUTO_INCREMENT,
  assignment_id BIGINT NOT NULL,
  student_id BIGINT NOT NULL,
  attempt_no INT UNSIGNED NOT NULL,
  is_late BOOLEAN NOT NULL DEFAULT FALSE,
  late_penalty_percent INT UNSIGNED NOT NULL DEFAULT 0,
  score DECIMAL(8,2) NOT NULL DEFAULT 0,
  idempotency_key CHAR(36) NOT NULL,
  submitted_at DATETIME NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_assignment_attempt_no (assignment_id, student_id, attempt_no),
  UNIQUE KEY uq_assignment_attempt_key (idempotency_key),
  KEY ix_assignment_attempts_student_date (student_id, submitted_at),
  CONSTRAINT fk_assignment_attempts_assignment FOREIGN KEY (assignment_id) REFERENCES assignments(id),
  CONSTRAINT fk_assignment_attempts_student FOREIGN KEY (student_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE submissions (
  id BIGINT NOT NULL AUTO_INCREMENT,
  student_id BIGINT NOT NULL,
  assignment_id BIGINT NOT NULL,
  assignment_attempt_id BIGINT NULL,
  question_id BIGINT NOT NULL,
  question_version_id BIGINT NOT NULL,
  type ENUM('mcq','code') NOT NULL,
  selected_option_ids JSON NULL,
  language VARCHAR(20) NULL,
  source_code MEDIUMTEXT NULL,
  attempt_no INT UNSIGNED NOT NULL,
  status ENUM('pending','grading','completed','failed') NOT NULL,
  score DECIMAL(8,2) NULL,
  is_late BOOLEAN NOT NULL DEFAULT FALSE,
  idempotency_key CHAR(36) NULL,
  submitted_at DATETIME NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_submission_attempt_question (assignment_attempt_id, question_id),
  UNIQUE KEY uq_assignment_question_attempt (assignment_id, student_id, question_id, attempt_no),
  UNIQUE KEY uq_submission_idempotency (idempotency_key),
  KEY ix_submissions_student_date (student_id, submitted_at),
  CONSTRAINT fk_submissions_student FOREIGN KEY (student_id) REFERENCES users(id),
  CONSTRAINT fk_submissions_assignment FOREIGN KEY (assignment_id) REFERENCES assignments(id),
  CONSTRAINT fk_submissions_assignment_attempt FOREIGN KEY (assignment_attempt_id) REFERENCES assignment_attempts(id),
  CONSTRAINT fk_submissions_question FOREIGN KEY (question_id) REFERENCES questions(id),
  CONSTRAINT fk_submissions_question_version FOREIGN KEY (question_version_id) REFERENCES question_versions(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
